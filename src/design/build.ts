// Generator of src/design/generated/tokens.css and tokens.json from src/design/tokens.ts.
// Pure: it returns the file contents and touches no file system, so
// src/design/tokens.build.test.ts can compare its output with the committed files.
// `pnpm tokens:build` (scripts/build-tokens.ts) writes them.

import { contrastRatio, formatOklch, hexToOklch, roundOklch } from './color';
import {
  COLOR_ROLES,
  CONTRAST_PAIRS,
  DEFAULT_THEME,
  DIM_TONES,
  MIN_LABEL_PX,
  PRINT_PAIRS,
  THEMES,
  THEME_COOKIE,
  colors,
  effects,
  fallbackFaces,
  fontFamilies,
  layout,
  linkStyles,
  motion,
  print,
  radius,
  typeScale,
  type ThemeName,
} from './tokens';

export const GENERATED_CSS_PATH = 'src/design/generated/tokens.css';
export const GENERATED_JSON_PATH = 'src/design/generated/tokens.json';

const HEADER = [
  '/*',
  ' * Generated by `pnpm tokens:build` from src/design/tokens.ts. Do not edit by hand:',
  ' * src/design/tokens.build.test.ts fails when this file differs from the generator output.',
  ' *',
  ' * Imported by src/app/globals.css after Tailwind. The dark theme is the default; the light',
  ' * theme applies when the system prefers it and no manual choice says "dark", or when the',
  ` * manual choice (cookie \`${THEME_COOKIE}\`, set as data-theme on <html>) says "light".`,
  ' * `.theme-dark` and `.theme-light` scope one theme to an element (the style guide).',
  ' */',
].join('\n');

/** Quotes a font family name unless it is a generic family or a var() reference. */
function family(name: string): string {
  const generic = ['serif', 'sans-serif', 'monospace', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace'];
  if (generic.includes(name) || name.startsWith('var(') || name.startsWith('-')) return name;
  return `'${name}'`;
}

export function fontStack(names: readonly string[]): string {
  return names.map(family).join(', ');
}

/** `11px` -> `0.6875rem`, also inside clamp(); font sizes follow the reader's text size. */
export function pxToRem(value: string): string {
  return value.replace(/(\d+(?:\.\d+)?)px/g, (_, px: string) => `${Number((Number(px) / 16).toFixed(4))}rem`);
}

function colorLines(theme: ThemeName, indent: string): string[] {
  return COLOR_ROLES.map((role) => {
    const hex = colors[theme][role];
    return `${indent}--${role}: ${formatOklch(hex)}; /* ${hex} */`;
  });
}

function effectLines(theme: ThemeName, indent: string): string[] {
  const e = effects[theme];
  return [
    `${indent}--scrim: ${e.scrim};`,
    `${indent}--elevation-pop: ${e['shadow-pop']};`,
    `${indent}--elevation-sheet: ${e['shadow-sheet']};`,
    `${indent}--elevation-raise: ${e['shadow-raise']};`,
  ];
}

function themeBlock(theme: ThemeName, selector: string, indent = ''): string[] {
  const inner = `${indent}  `;
  return [
    `${indent}${selector} {`,
    `${inner}color-scheme: ${theme};`,
    ...colorLines(theme, inner),
    ...effectLines(theme, inner),
    `${indent}}`,
  ];
}

export function buildCss(): string {
  const other: ThemeName = DEFAULT_THEME === 'dark' ? 'light' : 'dark';
  const out: string[] = [HEADER, ''];

  out.push('/* Size-matched fallback faces (plan §5.3): no layout shift while the web fonts load. */');
  for (const face of fallbackFaces) {
    out.push(
      '@font-face {',
      `  font-family: '${face.family}';`,
      `  src: ${face.local.map((name) => `local('${name}')`).join(', ')};`,
      `  size-adjust: ${face.sizeAdjust};`,
      `  ascent-override: ${face.ascentOverride};`,
      `  descent-override: ${face.descentOverride};`,
      `  line-gap-override: ${face.lineGapOverride};`,
      '}',
    );
  }
  out.push('');

  out.push(`/* Themes: ${DEFAULT_THEME} by default; ${other} by system preference or manual choice. */`);
  out.push(...themeBlock(DEFAULT_THEME, ':root'));
  out.push(`@media (prefers-color-scheme: ${other}) {`);
  out.push(...themeBlock(other, `:root:not([data-theme='${DEFAULT_THEME}'])`, '  '));
  out.push('}');
  out.push(...themeBlock(other, `:root[data-theme='${other}']`));
  out.push('/* Scoped themes: a panel that shows one theme inside the other (the style guide). */');
  for (const theme of THEMES) out.push(...themeBlock(theme, `.theme-${theme}`));
  out.push('');

  out.push('/* Theme-independent tokens. */');
  out.push(':root {');
  out.push('  /* Print (plan §5.2). */');
  for (const [name, hex] of Object.entries(print)) {
    out.push(`  --print-${name.replace(/^print-/, '')}: ${formatOklch(hex)}; /* ${hex} */`);
  }
  out.push('  /* Chinese names use system CJK fonts (plan §5.3); Traditional unless lang="zh-Hans". */');
  out.push(`  --font-cjk-serif: ${fontStack(fontFamilies['cjk-serif-hant'])};`);
  out.push(`  --font-cjk-sans: ${fontStack(fontFamilies['cjk-sans-hant'])};`);
  out.push('  /* Layout of the app shell (plan §5.8 (b)). */');
  for (const [name, value] of Object.entries(layout)) out.push(`  --${name}: ${value};`);
  out.push('  /* Motion (plan §5.8 (e)). */');
  for (const [name, value] of Object.entries(motion.duration)) out.push(`  --duration-${name}: ${value};`);
  out.push('  /* Link styles by verification state (plan §4.6): dash and width. */');
  for (const [state, style] of Object.entries(linkStyles)) {
    const key = state.replace(/_/g, '-');
    out.push(`  --link-${key}-dash: ${style.dash ?? 'none'};`);
    out.push(`  --link-${key}-width: ${style.width}px;`);
  }
  out.push('}');
  out.push('/*');
  out.push(' * Aliases of theme colours. A custom property resolves var() where it is declared, so they');
  out.push(' * are declared again on every element that sets a theme (a scoped panel keeps its colours).');
  out.push(' */');
  out.push(`:root, ${THEMES.map((theme) => `.theme-${theme}`).join(', ')} {`);
  out.push('  /* Solid dimming tones (plan §4.7): never opacity. */');
  for (const [name, role] of Object.entries(DIM_TONES)) out.push(`  --dim-${name}: var(--${role});`);
  out.push('  /* Link colours by verification state (plan §4.6): stroke and seal, then the text label. */');
  for (const [state, style] of Object.entries(linkStyles)) {
    const key = state.replace(/_/g, '-');
    out.push(`  --link-${key}-color: var(--${style.color});`);
    out.push(`  --link-${key}-label: var(--${style.labelColor});`);
  }
  out.push('}');
  out.push(':lang(zh-Hans) {');
  out.push(`  --font-cjk-serif: ${fontStack(fontFamilies['cjk-serif-hans'])};`);
  out.push(`  --font-cjk-sans: ${fontStack(fontFamilies['cjk-sans-hans'])};`);
  out.push('}');
  out.push('@media (prefers-reduced-motion: reduce) {');
  out.push('  :root {');
  for (const name of Object.keys(motion.duration)) out.push(`    --duration-${name}: 0ms;`);
  out.push('  }');
  out.push('}');
  out.push('');

  out.push('/*');
  out.push(' * Tailwind theme. `inline` makes utilities use the values directly, so a theme switch');
  out.push(' * only changes the variables above. The default palette, fonts, sizes, radii and');
  out.push(' * shadows are cleared: only the semantic tokens exist.');
  out.push(' */');
  out.push('@theme inline {');
  out.push('  --color-*: initial;');
  for (const role of COLOR_ROLES) out.push(`  --color-${role}: var(--${role});`);
  out.push('  --color-scrim: var(--scrim);');
  out.push('  --color-transparent: transparent;');
  out.push('  --color-current: currentColor;');
  out.push('');
  out.push('  --font-*: initial;');
  out.push(`  --font-display: ${fontStack(fontFamilies.display)};`);
  out.push(`  --font-sans: ${fontStack(fontFamilies.text)};`);
  out.push(`  --font-mono: ui-monospace, 'SFMono-Regular', 'Cascadia Mono', 'Liberation Mono', monospace;`);
  out.push('');
  out.push('  --text-*: initial;');
  for (const [name, step] of Object.entries(typeScale)) {
    out.push(`  --text-${name}: ${pxToRem(step.size)};`);
    out.push(`  --text-${name}--line-height: ${step.lineHeight};`);
    if (step.letterSpacing) out.push(`  --text-${name}--letter-spacing: ${step.letterSpacing};`);
    if (step.weight) out.push(`  --text-${name}--font-weight: ${step.weight};`);
  }
  out.push('');
  out.push('  --radius-*: initial;');
  for (const [name, value] of Object.entries(radius)) out.push(`  --radius-${name}: ${value};`);
  out.push('');
  out.push('  --shadow-*: initial;');
  out.push('  --shadow-pop: var(--elevation-pop);');
  out.push('  --shadow-sheet: var(--elevation-sheet);');
  out.push('  --shadow-raise: var(--elevation-raise);');
  out.push('');
  for (const [name, value] of Object.entries(motion.easing)) out.push(`  --ease-${name}: ${value};`);
  out.push('');
  out.push('  --spacing-touch: var(--touch);');
  out.push('  --spacing-tab: var(--tab-h);');
  out.push('  --spacing-top: var(--top-h);');
  out.push('  --spacing-rail: var(--rail-w);');
  out.push('  --container-content: var(--content-max);');
  out.push('}');
  out.push('');
  return out.join('\n');
}

/** Machine-readable tokens for the future mobile app (plan §6.8). */
export function buildJson(): string {
  const themeColors = Object.fromEntries(
    THEMES.map((theme) => [
      theme,
      Object.fromEntries(
        COLOR_ROLES.map((role) => {
          const hex = colors[theme][role];
          const { l, c, h } = roundOklch(hexToOklch(hex));
          return [role, { hex, oklch: { l, c, h } }];
        }),
      ),
    ]),
  );
  const contrast = Object.fromEntries(
    THEMES.map((theme) => [
      theme,
      CONTRAST_PAIRS.map((pair) => ({
        fg: pair.fg,
        bg: pair.bg,
        min: pair.min,
        ratio: Math.round(contrastRatio(colors[theme][pair.fg], colors[theme][pair.bg]) * 100) / 100,
      })),
    ]),
  );
  const data = {
    $comment: 'Generated by `pnpm tokens:build` from src/design/tokens.ts. Do not edit by hand.',
    direction: 'Ink Register',
    defaultTheme: DEFAULT_THEME,
    themeCookie: THEME_COOKIE,
    colors: themeColors,
    effects,
    dimTones: DIM_TONES,
    print,
    printContrast: PRINT_PAIRS.map((pair) => ({
      ...pair,
      ratio: Math.round(contrastRatio(print[pair.fg], print[pair.bg]) * 100) / 100,
    })),
    contrast,
    fontFamilies,
    fallbackFaces,
    typeScale,
    minLabelPx: MIN_LABEL_PX,
    radius,
    layout,
    motion,
    linkStyles,
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}
