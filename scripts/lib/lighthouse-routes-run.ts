interface Median {
  lcp: number;
  cls: number;
  tbt: number;
  fcp: number;
}

/** What scripts/lighthouse.mjs --plan writes. */
interface PlanResults {
  lighthouse: string;
  throttling: string;
  limits: Record<string, number>;
  routes: { label: string; runs: number; median: Median | null; ok: boolean; error: string | null }[];
}

function args(): Record<string, string> {
  return Object.fromEntries(
    process.argv.slice(2).map((arg) => {
      const [key, ...rest] = arg.replace(/^--/, '').split('=');
      return [key!, rest.join('=')];
    }),
  );
}

/** A session row for the user, as the cookie Better Auth reads (staff: second factor passed). */
async function sessionCookie(userId: string, staff: boolean): Promise<string> {
  const raw = randomBytes(24).toString('hex');
  await getDb()
    .insert(authSession)
    .values({ id: uuidv7(), userId, token: raw, expiresAt: new Date(Date.now() + 3_600_000), twoFactorVerifiedAt: staff ? new Date() : null });
  return `wcr.session_token=${encodeURIComponent(await signedSessionToken(raw, process.env.BETTER_AUTH_SECRET!))}`;
}

async function userIdOf(email: string): Promise<string> {
  const rows = await getDb().select({ id: authUser.id }).from(authUser).where(eq(authUser.email, email));
  if (!rows[0]) throw new Error(`no account ${email}: run pnpm db:seed on this database`);
  return rows[0].id;
}

function principal(id: string, email: string): Principal {
  return {
    user: { id, email, emailVerified: true, role: 'user', twoFactorEnabled: false },
    session: { id: uuidv7(), expiresAt: new Date(Date.now() + 3_600_000), twoFactorVerifiedAt: null },
    via: 'bearer',
  };
}

/** The cookie of each account the routes need. */
async function cookies(): Promise<Map<Account, string>> {
  const out = new Map<Account, string>();
  for (const account of new Set(MAIN_ROUTES.flatMap((r) => (r.as ? [r.as] : [])))) {
    if (account === 'new') {
      // A confirmed account that has given the sign-up consents and has no profile yet.
      const id = uuidv7();
      const email = `demo-perf-web-${randomBytes(4).toString('hex')}@example.test`;
      await getDb().insert(authUser).values({ id, email, emailVerified: true });
      await recordConsents(principal(id, email), { kinds: [...SIGN_UP_CONSENTS] }, META);
      out.set(account, await sessionCookie(id, false));
    } else if (account === 'admin') {
      const staff = DEMO_STAFF_ACCOUNTS.find((a) => a.role === 'admin')!;
      out.set(account, await sessionCookie(await userIdOf(demoAccountEmail(staff.slug)), true));
    } else {
      out.set(account, await sessionCookie(await userIdOf(demoAccountEmail(account)), false));
    }
  }
  return out;
}

/** A fresh invitation's token: a new fictional account with a profile lists a teacher not here yet. */
async function invitationToken(): Promise<string> {
  const inviter = await member('perf-web-inviter');
  const p = principal(inviter.account.id, inviter.account.email);
  await recordConsents(p, { kinds: [...SIGN_UP_CONSENTS] }, META);
  const lineage = await getDb().execute<{ id: string }>(sql`SELECT id::text AS id FROM lineage WHERE slug = 'demo-lineage-c'`);
  const email = `demo-perf-web-invited-${randomBytes(4).toString('hex')}@example.test`;
  await inviteTeacher(
    p,
    { teacherName: 'Demo Invited Teacher', lineageId: lineage.rows[0]!.id, periods: [{ from: '2012-09', to: null, ongoing: true }], email, evidenceIds: [], idempotencyKey: randomBytes(12).toString('hex') },
    META,
  );
  const rows = await getDb().execute<{ data: EmailSendJob }>(sql`
    SELECT j.data FROM pgboss.job j JOIN email_delivery d ON d.id::text = j.data ->> 'deliveryId'
     WHERE j.name = 'email.send' AND d.template = 'invitation' AND d.to_email = ${email}
     ORDER BY d.created_at DESC LIMIT 1`);
  if (!rows.rows[0]) throw new Error('the invitation e-mail was not queued');
  return new URL((jobTemplateData(rows.rows[0].data) as { url: string }).url).pathname.replace('/invite/', '');
}

export function replaceWebSection(text: string, section: string): string {
  const start = text.indexOf(WEB_SECTION_START);
  const end = text.indexOf(WEB_SECTION_END);
  if (start < 0 || end < start) return `${text.trimEnd()}\n\n${section}\n`;
  return `${text.slice(0, start)}${section}${text.slice(end + WEB_SECTION_END.length)}`;
}

function report(results: PlanResults, date: string): string {
  const lcpLimit = results.limits['largest-contentful-paint']!;
  const clsLimit = results.limits['cumulative-layout-shift']!;
  const rows = MAIN_ROUTES.map((route, i) => {
    const r = results.routes[i]!;
    const who = route.as ? ` (${route.as === 'new' ? 'нов акаунт без профил' : route.as})` : '';
    const m = r.median;
    const cells = m ? `${Math.round(m.lcp)} ms | ${m.cls.toFixed(3)} | ${Math.round(m.tbt)} ms | ${Math.round(m.fcp)} ms` : '— | — | — | —';
    return `| ${route.screen} | \`${route.path}\`${who} | ${cells} | ${r.runs} | ${r.ok ? 'да' : `**не**${r.error ? ` (${r.error})` : ''}`} |`;
  });
  const measured = MAIN_ROUTES.map((route, i) => ({ route, m: results.routes[i]!.median })).filter((x): x is { route: MainRoute; m: Median } => x.m !== null);
  const worst = [...measured].sort((a, b) => b.m.lcp - a.m.lcp)[0];
  const worstCls = [...measured].sort((a, b) => b.m.cls - a.m.cls)[0];
  return [
    WEB_SECTION_START,
    '',
    `### Lighthouse в мобилен профил: всички основни маршрути (${date})`,
    '',
    `Lighthouse ${results.lighthouse}, мобилен профил (4× по-бавен процесор и бавна 4G мрежа, ${results.throttling} throttling), срещу \`next start\` на тази версия с тестовите данни (\`pnpm perf:web\`, \`scripts/verify.d/M13.sh\`). Страниците зад вход се мерят с вход: сесия на демо акаунт, а на персонала с минат втори фактор. Праговете са тези на \`lighthouserc.json\`: LCP ≤ ${lcpLimit} ms и CLS ≤ ${clsLimit}. Всеки маршрут се пуска веднъж; маршрут над праг се пуска още два пъти и решава медианата от трите. TBT е лабораторният заместител на INP и е само за сведение.`,
    '',
    '| Екран (план §5.5) | Адрес | LCP | CLS | TBT | FCP | Пускания | В бюджета |',
    '|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
    worst && worstCls ? `Най-бавен LCP: ${worst.route.screen} (\`${worst.route.path}\`), ${Math.round(worst.m.lcp)} ms. Най-голям CLS: ${worstCls.route.screen}, ${worstCls.m.cls.toFixed(3)}.` : '',
    '',
    WEB_SECTION_END,
  ].join('\n');
}

export async function main(): Promise<void> {
  loadDotEnv(path.resolve('.env'));
  const a = args();
  const base = (a.base ?? '').replace(/\/$/, '');
  if (!base) throw new Error('usage: pnpm perf:web --base=http://127.0.0.1:<port> [--chrome-path=<chrome>] [--stdout]');
  if (!process.env.BETTER_AUTH_SECRET) throw new Error('BETTER_AUTH_SECRET is not set (the session cookies are signed with it)');

  const jar = await cookies();
  const focus = (await getDb().execute<{ id: string }>(sql`SELECT id::text AS id FROM person WHERE slug = 'demo-two-lineages'`)).rows[0]?.id;
  if (!focus) throw new Error('no demo-two-lineages: run pnpm db:seed on this database');
  const invite = await invitationToken();
  await closeDb();

  const dir = mkdtempSync(path.join(tmpdir(), 'wcr-perf-web-'));
  let results: PlanResults;
  let status: number | null;
  try {
    const plan = {
      base,
      routes: MAIN_ROUTES.map((route) => ({
        label: `${route.path}${route.as ? ` as ${route.as}` : ''}`,
        path: route.path.replace('{focus}', focus).replace('{invite}', invite),
        cookie: route.as ? jar.get(route.as) : undefined,
      })),
    };
    writeFileSync(path.join(dir, 'plan.json'), JSON.stringify(plan), { mode: 0o600 });
    const run = spawnSync(
      process.execPath,
      ['scripts/lighthouse.mjs', '--config=lighthouserc.json', `--plan=${path.join(dir, 'plan.json')}`, `--results=${path.join(dir, 'results.json')}`, ...(a['chrome-path'] ? [`--chrome-path=${a['chrome-path']}`] : [])],
      { stdio: 'inherit' },
    );
    status = run.status;
    if (!existsSync(path.join(dir, 'results.json'))) throw new Error(`scripts/lighthouse.mjs ended without results (exit ${String(run.status ?? run.signal)})`);
    results = JSON.parse(readFileSync(path.join(dir, 'results.json'), 'utf8')) as PlanResults;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  const section = report(results, new Date().toISOString().slice(0, 10));
  if (process.argv.includes('--stdout')) {
    console.log(section);
  } else {
    writeFileSync(OUTPUT, replaceWebSection(existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '', section));
    console.log(`perf:web: wrote ${OUTPUT}`);
  }
  if (status !== 0) process.exitCode = 1;
}
